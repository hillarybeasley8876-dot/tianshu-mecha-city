"""Build the Tianshu hero3 mech end to end (hero-v3).

    tools/blender.sh run blender/hero3/build_hero3.py -- [--stop-after=rig|bind|export]
    tools/blender.sh run blender/hero3/build_hero3.py -- --debug      (flat-coloured plates)

Pipeline (briefs/hero-v3.md):
  1. segment  the textured Tripo mesh into rigid armour plates, one bone each, capped (segment.py)
  2. rig      the measured mech skeleton, joint mechanisms, weapons (hero3_rig/joints/gear.py)
  3. bind     join the plates, one vertex group per bone at weight 1.0 (rigid, never tears)
  4. export   game/player/model/hero3/hero3.glb + hero3_lod1.glb + hero3_sockets.gd

Clips are authored separately (anims/); the export carries whatever actions exist.
"""
import argparse
import os
import sys

import bpy

sys.path.insert(0, os.path.expanduser("~/m/mecha-city/blender/hero3"))
sys.path.insert(0, os.path.expanduser("~/m/mecha-city/blender"))
import hero3_bones  # noqa: E402
import hero3_cap  # noqa: E402
import hero3_fit  # noqa: E402
import hero3_gear  # noqa: E402
import hero3_joints  # noqa: E402
import hero3_lib as H  # noqa: E402
import hero3_rig  # noqa: E402
import hero3_sleeve  # noqa: E402
import segment  # noqa: E402
from lib import common  # noqa: E402

OUT_DIR = os.path.join(H.ROOT, "game", "player", "model", "hero3")
LOD0_TEX = 4096          ## the brief asks for the 8K albedo baked down to 4K, PBR kept
LOD1_TEX = 2048
STAGES = ["rig", "bind", "export"]


def parse_args():
    argv = sys.argv[sys.argv.index("--") + 1:]
    p = argparse.ArgumentParser()
    p.add_argument("--stop-after", default="export", choices=STAGES)
    p.add_argument("--debug", action="store_true")
    return p.parse_args(argv)


def write_sockets(rows) -> str:
    """Emit the socket table as a GDScript const so hero3_model.gd never guesses an offset."""
    lines = ["# GENERATED by blender/hero3/build_hero3.py -- do not edit by hand.",
             "## HeroModel sockets (CONTRACTS §5): bone + offset in bone space, metres / degrees.",
             "class_name Hero3Sockets", "", "const TABLE: Array = ["]
    for name, bone, pos, rot in rows:
        lines.append('\t{"%s": {"bone": "%s", "pos": Vector3(%.4f, %.4f, %.4f), '
                     '"rot": Vector3(%.2f, %.2f, %.2f)}},' % (
                         name, bone, pos.x, pos.y, pos.z, rot.x, rot.y, rot.z))
    lines.append("]")
    lines.append("")
    path = os.path.join(OUT_DIR, "hero3_sockets.gd")
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(path, "w") as fh:
        fh.write("\n".join(lines))
    print("WROTE %s (%d sockets)" % (path, len(rows)))
    return path


def main() -> None:
    args = parse_args()
    common.reset()
    bpy.context.scene.render.fps = 60
    body = H.only_mesh(H.load_glb(segment.BODY_GLB), "body")
    body.name = "Hero3Source"
    parts = sorted([o for o in H.load_glb(segment.PARTS_GLB) if o.type == "MESH"],
                   key=lambda o: o.name)
    segment.stage_body(body, parts)
    H.decimate(body, segment.WORK_TRIS)
    segment.stage_align(body, parts)
    for obj in parts:
        obj.name = "Seg_" + obj.name.replace("tripo_part_", "p")
    labels = segment.stage_label(body, parts)
    segment.stage_final_scale(body, parts, labels)
    segment.stage_report(body, parts, labels)
    bone_ids, names, _ = segment.assign_bones(body, parts, labels)
    plates = segment.split_by_bone(body, bone_ids, names, colour=args.debug)
    # the collars band every cut rim, so they must be measured on the body BEFORE it is deleted
    collars = hero3_sleeve.build(body, bone_ids, names)
    # the body was already decimated to the LOD0 budget BEFORE the cut, so the plates share their
    # cut boundaries exactly; capping twice closes the rims and then the pinholes the caps opened
    hero3_cap.cap_pieces(plates)
    hero3_cap.cap_pieces(plates)
    print("PLATES %d, %d tris (budget %d, no post-cut decimation)"
          % (len(plates), sum(H.tri_count(p) for p in plates), segment.LOD0_TRIS))
    bpy.data.objects.remove(body, do_unlink=True)
    for obj in parts:
        bpy.data.objects.remove(obj, do_unlink=True)

    arm = hero3_rig.build_armature()
    # every internal part is fitted to the armour that surrounds it, measured off the plates
    plates_by_bone = {obj.name.replace("H3_", ""): obj for obj in plates}
    bones = hero3_bones.bone_map()
    mechanisms, pistons = hero3_joints.build(arm, plates_by_bone)
    cores = hero3_fit.build_cores(plates_by_bone, bones)
    gear = hero3_gear.build()
    extras = mechanisms + pistons + cores + collars
    if args.stop_after == "rig":
        H.export_glb(os.path.join(H.TMP, "stage_rig.glb"), plates + extras, animations=False)
        return

    # the plates, mechanisms and cores are ONE mesh (one draw call per material); the weapons stay
    # separate nodes so set_saber_drawn and the rifle swap can show and hide them
    bound, arm = hero3_rig.join_pieces(plates + extras)
    hero3_rig.bind(bound, arm)
    weapons = hero3_rig.bind_parts(arm, {
        "Hero3Saber": gear["saber"], "Hero3Rifle": gear["rifle"], "Hero3Shield": gear["shield"]})
    rows = hero3_rig.socket_table(arm)
    if args.stop_after == "bind":
        H.export_glb(os.path.join(H.TMP, "stage_bind.glb"), [arm, bound] + weapons, animations=False)
        return

    write_sockets(rows)
    for name, w, h in H.resize_images(LOD0_TEX, only=H.image_names(bound)):
        print("TEXTURE %-34s -> %dx%d" % (name, w, h))
    lod1 = bound.copy()
    lod1.data = bound.data.copy()
    lod1.name = "Hero3BodyLod1"
    bpy.context.scene.collection.objects.link(lod1)
    print("LOD1 %d tris" % H.decimate(lod1, segment.LOD1_TRIS))
    H.export_glb(os.path.join(OUT_DIR, "hero3.glb"), [arm, bound] + weapons)
    H.resize_images(LOD1_TEX, only=H.image_names(lod1))
    H.export_glb(os.path.join(OUT_DIR, "hero3_lod1.glb"), [arm, lod1] + weapons, animations=False)
    for path in ("hero3.glb", "hero3_lod1.glb"):
        full = os.path.join(OUT_DIR, path)
        print("FILE %-16s %.1f MB" % (path, os.path.getsize(full) / 1e6))
    print("REPORT bones=%d plates=%d tris=%d crest=%.2f m" % (
        len(arm.data.bones), len(plates), H.tri_count(bound), 16.0))


if __name__ == "__main__":
    main()
